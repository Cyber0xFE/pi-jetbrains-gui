type Key = keyof typeof messages.en;

interface I18nValue {
  language: Language;
  t: (key: Key, values?: Values) => string;
}

const I18nContext = createContext<I18nValue>({
  language: "legacy",
  t: (key, values) => interpolate(legacyMessages[key], values),
});

export function normalizeLanguage(language?: string | null): Language {
  if (language === "zh") return "zh";
  if (language === "en") return "en";
  return "legacy";
}

export function I18nProvider({ language, children }: { language?: string | null; children: ReactNode }): JSX.Element {
  const normalized = normalizeLanguage(language);
  const value = useMemo<I18nValue>(() => ({
    language: normalized,
    t: (key, values) => interpolate(normalized === "legacy" ? legacyMessages[key] : messages[normalized][key], values),
  }), [normalized]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

function interpolate(template: string, values?: Values): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
